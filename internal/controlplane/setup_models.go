func sha256Hex(s string) string {
	sum := sha256.Sum256([]byte(s))
	return hex.EncodeToString(sum[:])
}

func migratedModelID(alias string) string {
	return "omahab-migrated-" + sha256Hex(alias)
}

func migratedCredentialName(legacyID string) string {
	return "omahab-migrated-" + sha256Hex(strings.TrimSpace(legacyID))
}

func seedCredentialName(sourceID string) string {
	return "omahab-seed-" + sha256Hex(strings.TrimSpace(sourceID))
}

func seedRoleID(alias string) string {
	return "omahab-seed-" + sha256Hex(strings.TrimSpace(alias))
}

// --- journal ---

func (b *Backend) handoffGet(ctx context.Context, key string) (string, error) {
	if b.db == nil {
		return "", fmt.Errorf("db not configured")
	}
	var v string
	err := b.db.QueryRowContext(ctx, `SELECT value FROM provider_model_handoff WHERE key = ?`, key).Scan(&v)
	if err != nil {
		return "", err
	}
	return v, nil
}

func (b *Backend) handoffSet(ctx context.Context, key, value string) error {
	if b.db == nil {
		return fmt.Errorf("db not configured")
	}
	_, err := b.db.ExecContext(ctx, `INSERT INTO provider_model_handoff(key, value) VALUES(?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value`, key, value)
	return err
}

func (b *Backend) handoffDel(ctx context.Context, key string) error {
	if b.db == nil {
		return nil
	}
	_, _ = b.db.ExecContext(ctx, `DELETE FROM provider_model_handoff WHERE key = ?`, key)
	return nil
}

func (b *Backend) handoffPhase(ctx context.Context) string {
	v, err := b.handoffGet(ctx, handoffPhaseKey)
	if err != nil {
		return ""
	}
	return strings.TrimSpace(v)
}

func (b *Backend) handoffSetPhase(ctx context.Context, phase string) error {
	if err := b.handoffSet(ctx, handoffVersionKey, handoffVersionVal); err != nil {
		return err
	}
	return b.handoffSet(ctx, handoffPhaseKey, phase)
}

func (b *Backend) handoffSetError(ctx context.Context, msg string) {
	msg = strings.TrimSpace(msg)
	if msg == "" {
		_ = b.handoffDel(ctx, handoffErrorKey)
		return
	}
	// Safe text only: callers must never include secrets.
	if len(msg) > 500 {
		msg = msg[:500]
	}
	_ = b.handoffSet(ctx, handoffErrorKey, msg)
}

