func staticLitellmBootstrap() string {
	return `# Generated by omahab — do not edit. Native DB ownership; models live in LiteLLM database.
model_list: []
general_settings:
  store_model_in_db: true
  store_prompts_in_spend_logs: false
litellm_settings:
  turn_off_message_logging: true
router_settings:
  num_retries: 0
  fallbacks: []
`
}

func (b *Backend) litellmConfigPaths() (finalPath, snapshotPath string) {
	dir := b.gatewayConfigDir()
	return filepath.Join(dir, "litellm.yaml"), filepath.Join(dir, "omahab-pre-handoff.yaml")
}

func (b *Backend) snapshotPreHandoffYAML() error {
	finalPath, snapshotPath := b.litellmConfigPaths()
	if _, err := os.Stat(snapshotPath); err == nil {
		return nil // never overwrite recovery snapshot on retry
	}
	raw, err := os.ReadFile(finalPath)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		return fmt.Errorf("read live litellm config: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(snapshotPath), 0o700); err != nil {
		return fmt.Errorf("mkdir config dir: %w", err)
	}
	if err := os.WriteFile(snapshotPath, raw, 0o600); err != nil {
		return fmt.Errorf("write pre-handoff snapshot: %w", err)
	}
	_ = os.Chmod(snapshotPath, 0o600)
	return nil
}

func (b *Backend) writeStaticBootstrapYAML() error {
	finalPath, _ := b.litellmConfigPaths()
	want := staticLitellmBootstrap()
	if raw, err := os.ReadFile(finalPath); err == nil && string(raw) == want {
		providers.ShareGatewayConfig(finalPath)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(finalPath), 0o700); err != nil {
		return fmt.Errorf("mkdir config dir: %w", err)
	}
	tmp, err := os.CreateTemp(filepath.Dir(finalPath), "litellm.yaml.*")
	if err != nil {
		return fmt.Errorf("stage static config: %w", err)
	}
	tmpName := tmp.Name()
	if _, err := tmp.WriteString(want); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmpName)
		return fmt.Errorf("write static config: %w", err)
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(tmpName)
		return fmt.Errorf("close static config: %w", err)
	}
	_ = os.Chmod(tmpName, 0o600)
	if err := os.Rename(tmpName, finalPath); err != nil {
		_ = os.Remove(tmpName)
		return fmt.Errorf("activate static config: %w", err)
	}
	providers.ShareGatewayConfig(finalPath)
	return nil
}

// restorePreHandoffYAML puts the pre-handoff gateway config back after a
// failed cutover verify, so the gateway never serves the empty bootstrap
// with nothing behind it. No snapshot (fresh installs) is a no-op.
func (b *Backend) restorePreHandoffYAML() error {
	finalPath, snapshotPath := b.litellmConfigPaths()
	raw, err := os.ReadFile(snapshotPath)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		return fmt.Errorf("read pre-handoff snapshot: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(finalPath), 0o700); err != nil {
		return fmt.Errorf("mkdir config dir: %w", err)
	}
	tmp, err := os.CreateTemp(filepath.Dir(finalPath), "litellm.yaml.*")
	if err != nil {
		return fmt.Errorf("stage restored config: %w", err)
	}
	tmpName := tmp.Name()
	if _, err := tmp.Write(raw); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmpName)
		return fmt.Errorf("write restored config: %w", err)
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(tmpName)
		return fmt.Errorf("close restored config: %w", err)
	}
	_ = os.Chmod(tmpName, 0o600)
	if err := os.Rename(tmpName, finalPath); err != nil {
		_ = os.Remove(tmpName)
		return fmt.Errorf("activate restored config: %w", err)
	}
	providers.ShareGatewayConfig(finalPath)
	return nil
}

// ensureLitellmSalt resolves the effective LITELLM_SALT_KEY per freeze semantics
// and persists it through the broker. It never regenerates during setup and
// never logs secret material. Returns the chosen salt (possibly empty when
// neither active nor broker material exists yet; caller then leaves env alone).
func (b *Backend) ensureLitellmSalt(ctx context.Context, existing map[string]string) string {
	active := strings.TrimSpace(existing["LITELLM_SALT_KEY"])
	if active != "" {
		// Keep byte-for-byte; mirror into broker so retries converge.
		if b.secrets != nil {
			if cur, err := b.secrets.RevealByName(ctx, "platform-app", "litellm_salt_key"); err != nil || strings.TrimSpace(cur) != active {
				_ = upsertSecret(ctx, b.secrets, "platform-app", "litellm_salt_key", active)
			}
		}
		return active
	}
	// No active salt: freeze current effective master key before any change.
	effectiveMaster := strings.TrimSpace(existing["LITELLM_MASTER_KEY"])
	if effectiveMaster == "" && b.secrets != nil {
		if v, err := b.secrets.RevealByName(ctx, "platform-app", "litellm_master_key"); err == nil {
			effectiveMaster = strings.TrimSpace(v)
		}
	}
	if effectiveMaster != "" {
		if b.secrets != nil {
			_ = upsertSecret(ctx, b.secrets, "platform-app", "litellm_salt_key", effectiveMaster)
		}
		return effectiveMaster
	}
	// Fresh install: use already-declared broker secret (materialized from
	// catalog secret_sources); never generate here.
	if b.secrets != nil {
		if v, err := b.secrets.RevealByName(ctx, "platform-app", "litellm_salt_key"); err == nil && strings.TrimSpace(v) != "" {
			return strings.TrimSpace(v)
		}
	}
	return ""
}

